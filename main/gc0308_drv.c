static const char *TAG = "gc0308";

static i2c_master_dev_handle_t s_dev = NULL;

// GC0308 常用寄存器
#define REG_PAGE_SEL    0xFE  // 页选择；写 0xF0 为软复位
#define REG_PID         0x00  // 芯片 ID
#define REG_OUTPUT_FMT  0x24  // 输出格式，低 4 位：0x06=RGB565
#define REG_CISCTL_MODE 0x14  // bit0=水平镜像，bit1=垂直翻转
#define REG_SUBSAMPLE_EN  0x53  // 页1：bit7=子采样使能
#define REG_SUBSAMPLE_MODE 0x54 // 页1：0x22 = 1/2 缩放
#define REG_SUBSAMPLE_EN2  0x55  // 页1：bit0=子采样使能2
#define REG_SUBSAMPLE_Y0 0x56
#define REG_SUBSAMPLE_Y1 0x57
#define REG_SUBSAMPLE_UV0 0x58
#define REG_SUBSAMPLE_UV1 0x59

// ---- I2C 基础读写：SCCB 就是标准 I2C，寄存器地址 8 位 ----
static esp_err_t reg_write(uint8_t reg, uint8_t val)
{
    uint8_t buf[2] = {reg, val};
    return i2c_master_transmit(s_dev, buf, sizeof(buf), 100);
}

static esp_err_t reg_read(uint8_t reg, uint8_t *val)
{
    return i2c_master_transmit_receive(s_dev, &reg, 1, val, 1, 100);
}

// 读-改-写：只修改 mask 指定的位，避免覆盖寄存器其他配置
static esp_err_t reg_set_bits(uint8_t reg, uint8_t mask, uint8_t value)
{
    uint8_t cur = 0;
    esp_err_t ret = reg_read(reg, &cur);
    if (ret != ESP_OK) {
        return ret;
    }
    return reg_write(reg, (uint8_t)((cur & ~mask) | (value & mask)));
}

