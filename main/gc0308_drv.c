static esp_err_t reg_write_table(const uint8_t regs[][2], size_t count)
{
    for (size_t i = 0; i < count; i++) {
        esp_err_t ret = reg_write(regs[i][0], regs[i][1]);
        if (ret != ESP_OK) {
            return ret;
        }
    }
    return ESP_OK;
}

esp_err_t gc0308_drv_init(void)
{
    esp_err_t ret;

    i2c_bus_init();
    if (!s_dev) {
        s_dev = i2c_bus_add_device(GC0308_I2C_ADDR);
        if (!s_dev) {
            ESP_LOGE(TAG, "add I2C device 0x%02x failed", GC0308_I2C_ADDR);
            return ESP_FAIL;
        }
    }

    // 1. 软件复位
    ret = reg_write(REG_PAGE_SEL, 0xF0);
    if (ret != ESP_OK) {
        ESP_LOGE(TAG, "software reset failed: 0x%x", ret);
        return ret;
    }
    vTaskDelay(pdMS_TO_TICKS(80));

    // 2. 写默认寄存器表
    ret = reg_write_table(gc0308_default_regs,
                          sizeof(gc0308_default_regs) / sizeof(gc0308_default_regs[0]));
    if (ret != ESP_OK) {
        ESP_LOGE(TAG, "default regs failed: 0x%x", ret);
        return ret;
    }
    vTaskDelay(pdMS_TO_TICKS(80));
    reg_write(REG_PAGE_SEL, 0x00);

    // 3. 读 PID 确认芯片
    uint8_t pid = 0;
    ret = reg_read(REG_PID, &pid);
    if (ret != ESP_OK || pid != GC0308_PID) {
        ESP_LOGE(TAG, "PID mismatch: expected 0x%02x, got 0x%02x", GC0308_PID, pid);
        return ESP_ERR_NOT_FOUND;
    }

    // 4. QVGA(320x240)：保持 VGA 窗口，用传感器内部 1/2 子采样输出
    //    窗口尺寸 = 分辨率 + 8（GC0308 硬件要求），VGA 窗口即 648x488
    static const uint8_t qvga_page0[][2] = {
        {0x05, 0x00}, {0x06, 0x00},  // ROW_START = 0
        {0x07, 0x00}, {0x08, 0x00},  // COL_START = 0
        {0x09, 0x01}, {0x0a, 0xE8},  // WIN_HEIGHT = 488
        {0x0b, 0x02}, {0x0c, 0x88},  // WIN_WIDTH  = 648
    };
    ret = reg_write_table(qvga_page0, sizeof(qvga_page0) / sizeof(qvga_page0[0]));
    if (ret != ESP_OK) {
        return ret;
    }

    ret = reg_write(REG_PAGE_SEL, 0x01);             // 切到页 1
    ret |= reg_set_bits(REG_SUBSAMPLE_EN, 0x80, 0x80);   // bit7 = 1：使能子采样
    ret |= reg_set_bits(REG_SUBSAMPLE_EN2, 0x01, 0x01);  // bit0 = 1：使能子采样 2
    ret |= reg_write(REG_SUBSAMPLE_MODE, 0x22);          // 1/2 缩放
    ret |= reg_write(REG_SUBSAMPLE_Y0, 0x00);
    ret |= reg_write(REG_SUBSAMPLE_Y1, 0x00);
    ret |= reg_write(REG_SUBSAMPLE_UV0, 0x00);
    ret |= reg_write(REG_SUBSAMPLE_UV1, 0x00);
    ret |= reg_write(REG_PAGE_SEL, 0x00);                // 回到页 0
    if (ret != ESP_OK) {
        ESP_LOGE(TAG, "QVGA subsample config failed: 0x%x", ret);
        return ret;
    }

    // 5. 输出格式 RGB565（只改低 4 位，保留高 4 位原有配置）
    ret = reg_set_bits(REG_OUTPUT_FMT, 0x0F, 0x06);
    if (ret != ESP_OK) {
        ESP_LOGE(TAG, "set RGB565 failed: 0x%x", ret);
        return ret;
    }

    // 6. 水平镜像，匹配屏幕方向（只改 bit0）
    ret = reg_set_bits(REG_CISCTL_MODE, 0x01, 0x01);
    if (ret != ESP_OK) {
        return ret;
    }

    ESP_LOGI(TAG, "GC0308 OK, PID=0x%02x", pid);
    return ESP_OK;
}
